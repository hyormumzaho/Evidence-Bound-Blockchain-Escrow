import { createRequire } from "node:module";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const { StandardMerkleTree } = require("@openzeppelin/merkle-tree");
const merkleRequire = createRequire(require.resolve("@openzeppelin/merkle-tree/package.json"));
const { keccak256 } = merkleRequire("ethereum-cryptography/keccak");

const here = dirname(fileURLToPath(import.meta.url));
const fixtureDir = join(here, "..", "test", "fixtures");
const ESCROW = "0x1111111111111111111111111111111111111111";
const LEAF_ENCODING = [
  "uint16",
  "uint256",
  "address",
  "uint256",
  "uint32",
  "uint32",
  "bytes32",
  "bytes32",
  "bytes32",
];

function keccakHex(text) {
  return `0x${Buffer.from(keccak256(Buffer.from(text))).toString("hex")}`;
}

const FILE_TYPE = keccakHex("evidencebound.file.v1");

function item(index, contentLabel, saltLabel, deliveryVersion) {
  return {
    schemaVersion: 1,
    chainId: 31337,
    escrowContract: ESCROW,
    escrowId: 7,
    deliveryVersion,
    itemIndex: index,
    evidenceType: FILE_TYPE,
    contentHash: keccakHex(contentLabel),
    salt: keccakHex(saltLabel),
  };
}

function valuesOf(leaves) {
  return leaves.map((leaf) => [
    leaf.schemaVersion,
    leaf.chainId,
    leaf.escrowContract,
    leaf.escrowId,
    leaf.deliveryVersion,
    leaf.itemIndex,
    leaf.evidenceType,
    leaf.contentHash,
    leaf.salt,
  ]);
}

const cases = [
  { name: "single", leaves: [item(0, "file-0", "salt-0", 1)] },
  { name: "pair", leaves: [item(0, "file-0", "salt-0", 1), item(1, "file-1", "salt-1", 1)] },
  {
    name: "triple",
    leaves: [item(0, "file-0", "salt-0", 1), item(1, "file-1", "salt-1", 1), item(2, "file-2", "salt-2", 1)],
  },
  {
    name: "five",
    leaves: [0, 1, 2, 3, 4].map((index) => item(index, `file-${index}`, `salt-${index}`, 3)),
  },
  {
    name: "duplicate-content",
    leaves: [item(0, "same-bytes", "salt-a", 4), item(1, "same-bytes", "salt-b", 4)],
  },
].map((entry) => {
  const tree = StandardMerkleTree.of(valuesOf(entry.leaves), LEAF_ENCODING);
  const leaves = entry.leaves.map((leaf, index) => {
    const proof = tree.getProof(index);
    const value = valuesOf([leaf])[0];
    if (!StandardMerkleTree.verify(tree.root, LEAF_ENCODING, value, proof)) {
      throw new Error(`Fixture ${entry.name} leaf ${index} did not verify`);
    }
    return { ...leaf, leafHash: tree.leafHash(value), proof };
  });
  return { name: entry.name, root: tree.root, leaves };
});

mkdirSync(fixtureDir, { recursive: true });
writeFileSync(
  join(fixtureDir, "merkle-vectors.json"),
  `${JSON.stringify(
    {
      schema: "evidencebound.merkle-vectors.v1",
      generator: "@openzeppelin/merkle-tree@1.0.8",
      leafEncoding: LEAF_ENCODING,
      sortLeaves: true,
      leafHash: "keccak256(keccak256(abi.encode(fields)))",
      note: "Salts in this file are deterministic test vectors, not production salts.",
      cases,
    },
    null,
    2,
  )}\n`,
);

function solLeaf(leaf) {
  return `MerkleVectors.Leaf(${leaf.schemaVersion}, ${leaf.chainId}, ${leaf.escrowContract}, ${leaf.escrowId}, ${leaf.deliveryVersion}, ${leaf.itemIndex}, ${leaf.evidenceType}, ${leaf.contentHash}, ${leaf.salt}, ${leaf.leafHash})`;
}

function solProof(proof) {
  if (proof.length === 0) return "        bytes32[] memory data;";
  const lines = [`        bytes32[] memory data = new bytes32[](${proof.length});`];
  proof.forEach((value, index) => {
    lines.push(`        data[${index}] = ${value};`);
  });
  return lines.join("\n");
}

function cascade(method, bodyForCase) {
  return cases
    .map((entry, index) => `        if (caseIndex == ${index}) {\n${bodyForCase(entry, index)}\n        }`)
    .join(" else ");
}

const solidity = `// SPDX-License-Identifier: MIT
// Generated by script/generate-merkle-fixtures.mjs. Do not edit by hand.
pragma solidity 0.8.38;

library MerkleVectors {
    struct Leaf {
        uint16 schemaVersion;
        uint256 chainId;
        address escrowContract;
        uint256 escrowId;
        uint32 deliveryVersion;
        uint32 itemIndex;
        bytes32 evidenceType;
        bytes32 contentHash;
        bytes32 salt;
        bytes32 leafHash;
    }

    function caseCount() internal pure returns (uint256) {
        return ${cases.length};
    }

    function leafCount(uint256 caseIndex) internal pure returns (uint256) {
        ${cascade("leafCount", (entry) => `            return ${entry.leaves.length};`)}
        revert("case");
    }

    function root(uint256 caseIndex) internal pure returns (bytes32) {
        ${cascade("root", (entry) => `            return ${entry.root};`)}
        revert("case");
    }

    function leaf(uint256 caseIndex, uint256 leafIndex) internal pure returns (Leaf memory) {
        ${cases
          .map((entry, index) => {
            const branches = entry.leaves
              .map((leaf, leafIndex) => `            if (leafIndex == ${leafIndex}) return ${solLeaf(leaf)};`)
              .join("\n");
            return `        if (caseIndex == ${index}) {\n${branches}\n        }`;
          })
          .join(" else ")}
        revert("leaf");
    }

    function proof(uint256 caseIndex, uint256 leafIndex) internal pure returns (bytes32[] memory) {
        ${cases
          .map((entry, index) => {
            const branches = entry.leaves
              .map((leaf, leafIndex) => `            if (leafIndex == ${leafIndex}) {\n${solProof(leaf.proof)}\n                return data;\n            }`)
              .join("\n");
            return `        if (caseIndex == ${index}) {\n${branches}\n        }`;
          })
          .join(" else ")}
        revert("proof");
    }
}
`;

writeFileSync(join(fixtureDir, "MerkleVectors.sol"), solidity);
console.log(`Wrote ${cases.length} Merkle vectors`);
for (const entry of cases) {
  console.log(`${entry.name}: ${entry.leaves.length} leaves root ${entry.root}`);
}
